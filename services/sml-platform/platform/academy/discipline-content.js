function splitNarration(text, maxCharacters = 3200) {
  const paragraphs = String(text || '').split(/\n\s*\n/).map((part) => part.trim()).filter(Boolean);
  const chunks = [];
  let current = '';
  for (const paragraph of paragraphs) {
    if (current && current.length + paragraph.length + 2 > maxCharacters) {
      chunks.push(current);
      current = '';
    }
    if (paragraph.length <= maxCharacters) {
      current = current ? `${current}\n\n${paragraph}` : paragraph;
      continue;
    }
    for (const sentence of paragraph.match(/[^.!?]+[.!?]+|[^.!?]+$/g) || [paragraph]) {
      const clean = sentence.trim();
      if (current && current.length + clean.length + 1 > maxCharacters) {
        chunks.push(current);
        current = '';
      }
      current = current ? `${current} ${clean}` : clean;
    }
  }
  if (current) chunks.push(current);
  return chunks;
}

